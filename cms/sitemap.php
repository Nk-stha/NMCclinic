<?php
declare(strict_types=1);

require_once __DIR__ . '/includes/auth.php';
require_once __DIR__ . '/includes/layout.php';
require_once __DIR__ . '/../includes/public_seo.php';

$admin = require_admin();
$toast = $_SESSION['sitemap_toast'] ?? null;
unset($_SESSION['sitemap_toast']);

if ($_SERVER['REQUEST_METHOD'] === 'POST') {
    if (!csrf_is_valid($_POST['csrf_token'] ?? null)) {
        $_SESSION['sitemap_toast'] = ['type' => 'error', 'message' => 'Invalid request. Please reload the page and try again.'];
    } else {
        $count = count(public_sitemap_urls());
        $_SESSION['sitemap_toast'] = ['type' => 'success', 'message' => 'Sitemap synced. The dynamic sitemap currently exposes ' . $count . ' public URLs.'];
    }

    header('Location: sitemap.php');
    exit;
}

try {
    $urls = public_sitemap_urls();
} catch (Throwable $exception) {
    $urls = [];
    $toast = ['type' => 'error', 'message' => 'Sitemap data is not available. Please confirm the latest schema has been imported.'];
}

cms_header('Sitemap', $admin, 'sitemap');
?>
<section class="content">
  <div class="page-head">
    <div>
      <h1>Sitemap</h1>
      <p>Review the live XML sitemap generated from existing public routes and CMS page update dates.</p>
    </div>
    <div style="display:flex;gap:12px;flex-wrap:wrap">
      <a class="secondary-btn" href="../sitemap.php" target="_blank" rel="noopener">Open XML</a>
      <form method="post" action="sitemap.php">
        <input type="hidden" name="csrf_token" value="<?= e(csrf_token()) ?>">
        <button class="primary-btn" style="width:auto" type="submit">
          <span class="material-symbols-outlined">sync</span>Sync Sitemap
        </button>
      </form>
    </div>
  </div>

  <?php if ($toast): ?>
    <div class="toast <?= e((string) $toast['type']) ?>" role="status"><?= e((string) $toast['message']) ?></div>
  <?php endif; ?>

  <section class="card">
    <div class="panel-head">
      <h2>Live Sitemap URLs</h2>
      <span class="tag"><?= count($urls) ?> total</span>
    </div>
    <?php if ($urls === []): ?>
      <div class="empty">No sitemap URLs found.</div>
    <?php else: ?>
      <div class="table-wrap">
        <table>
          <thead>
            <tr>
              <th>URL</th>
              <th>Last Modified</th>
              <th>Priority</th>
            </tr>
          </thead>
          <tbody>
            <?php foreach ($urls as $url): ?>
              <tr>
                <td><a href="<?= e((string) $url['loc']) ?>" target="_blank" rel="noopener"><?= e((string) $url['loc']) ?></a></td>
                <td><?= e((string) $url['lastmod']) ?></td>
                <td><?= e((string) $url['priority']) ?></td>
              </tr>
            <?php endforeach; ?>
          </tbody>
        </table>
      </div>
    <?php endif; ?>
  </section>

  <section class="card form-card" style="margin-top:24px">
    <h2><span class="material-symbols-outlined">info</span>Dynamic Source</h2>
    <p class="hint">The public sitemap is generated by <code>/sitemap.php</code> on every request. The sync button verifies the current generated URL set and shows the latest count; it does not write a static XML file.</p>
    <p class="hint">Current source includes public static routes that exist in the project and published CMS page update dates. Doctor, specialty, and blog detail records should be added only after matching public detail routes exist.</p>
  </section>
</section>
<?php cms_footer(); ?>
